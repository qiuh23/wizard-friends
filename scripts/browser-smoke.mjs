import { chromium, expect } from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('.local', { recursive: true });
const base = process.env.GAME_URL || 'http://127.0.0.1:5173/';
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true });
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
page.on('pageerror', e => errors.push(e.message));
await page.goto(base);
await page.locator('.scene-host.ready canvas').waitFor({ timeout: 20000 });
if (await page.locator('.facts, .intro, .how, footer').count()) throw new Error('Homepage contains marketing UI');
if (await page.locator('#join-form').isVisible()) throw new Error('Join form must start collapsed');
await page.locator('#join-menu').click();
await page.locator('#room-input').fill('ABCD2345');
await page.locator('#rules').click();
await page.locator('#close-rules').click();
if (await page.locator('#room-input').inputValue() !== 'ABCD2345') throw new Error('Menu lost room draft');
await page.locator('#join-menu').click();
if (await page.evaluate(() => document.documentElement.scrollHeight > innerHeight)) throw new Error('Desktop menu exceeds viewport');
await page.screenshot({ path: '.local/smoke-desktop.png', fullPage: true });
await page.locator('#nickname').fill('测试巫师');
await page.locator('#practice').click();
await page.locator('.lobby-scene .scene-host.ready canvas').waitFor();
if (await page.locator('.seats .seat').count() !== 6) throw new Error('Lobby must have six seats');
await page.locator('[data-remove]').last().click();
if (await page.locator('#start').isEnabled()) throw new Error('Two players cannot start');
await page.locator('#addbot').click();
if (!await page.locator('#start').isEnabled()) throw new Error('Three players should be able to start');
await page.screenshot({ path: '.local/smoke-lobby-desktop.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.local/smoke-lobby-mobile.png', fullPage: true });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Lobby mobile overflow');
await page.setViewportSize({ width: 1440, height: 1000 });
if (!await page.locator('input[name="short"][value="true"]').isChecked()) throw new Error('Practice must default to five rounds');
await page.locator('#start').click();
await page.locator('.table .scene-host.ready canvas').waitFor();
const tableFillsScreen = await page.locator('.table').evaluate(el => {
  const r = el.getBoundingClientRect();
  return r.x === 0 && r.y === 0 && Math.abs(r.width - innerWidth) < 2 && Math.abs(r.height - innerHeight) < 2;
});
if (!tableFillsScreen || await page.locator('.game-layout aside').isVisible()) throw new Error('Game must start with a full viewport table and closed score panel');
if (await page.locator('.trump-marker').count()) throw new Error('Old corner trump marker must be removed');
if (await page.locator('.opponents .player').count() !== 2 || await page.locator('.opponents .self').count()) throw new Error('Only the other two players belong around the table');
if (!await page.locator('.own-status').isVisible()) throw new Error('Your own seat and target must remain beside your hand');
const waitingCards = page.locator('.hand .card');
await waitingCards.first().waitFor();
if (!await waitingCards.evaluateAll(cards => cards.every(card => {
  const style = getComputedStyle(card);
  return style.opacity === '1' && style.filter === 'none';
}))) throw new Error('Waiting cards must retain full brightness and saturation');
if (!await waitingCards.first().isEnabled()) throw new Error('Waiting cards must remain inspectable');
await waitingCards.first().click();
if (!await page.locator('.selected-preview').isVisible() || await page.locator('#confirm-play').isEnabled()) throw new Error('Inspecting a waiting card must show its preview without permitting a play');
await page.screenshot({ path: '.local/smoke-fullscreen-table.png', fullPage: true });
for (let step = 0; step < 400; step++) {
  const trumpDisplay = await page.locator('.table').evaluate(el => ({
    suit: el.dataset.trumpSuit, color: el.style.getPropertyValue('--trump-color'),
    label: el.querySelector('.table-trump')?.textContent,
  }));
  const colors = { blue: '#60b8ff', red: '#ff6668', green: '#70d79d', yellow: '#f3cf66', none: '#ffffff' };
  if (trumpDisplay.color !== colors[trumpDisplay.suit] || !trumpDisplay.label) throw new Error('Table trump indicator is missing or mismatched');
  if (await page.locator('#rematch').count()) break;
  if (await page.locator('[data-trump]').count()) await page.locator('[data-trump]').first().click();
  else if (await page.locator('[data-bid]').count()) await page.locator('[data-bid]').first().click();
  else if (await page.locator('.hand .playable').count()) {
    await page.locator('.hand .playable').first().click();
    await page.locator('#confirm-play').click();
  }
  else if (await page.locator('#next').count()) await page.locator('#next').click();
  else await page.waitForTimeout(180);
}
if (!await page.locator('#rematch').count()) throw new Error('Practice game did not finish');
if (await page.locator('#rules-form').count()) throw new Error('Rules must remain fixed during play');
if (await page.locator('.scene-host canvas').count() !== 1) throw new Error('Expected one persistent 3D canvas');
await page.screenshot({ path: '.local/smoke-game.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.local/smoke-mobile-game.png', fullPage: true });
await page.locator('#chat-toggle').click();
await page.locator('#chat-input').fill('手机聊天测试');
await page.locator('#chat-form button').click();
await page.screenshot({ path: '.local/smoke-chat-mobile.png', fullPage: true });
await page.locator('#close-chat').click();
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile horizontal overflow');
if (await page.locator('.close-scores').isVisible()) await page.locator('.close-scores').click();
await page.locator('#rematch').click();
await page.locator('#start').waitFor();
if (!await page.locator('#rules-form').count()) throw new Error('Rematch must return to lobby rule selection');
const mobile = await ctx.newPage();
await mobile.setViewportSize({ width: 390, height: 844 });
await mobile.goto(base);
await mobile.locator('.scene-host.ready canvas').waitFor({ timeout: 20000 });
await mobile.screenshot({ path: '.local/smoke-mobile.png', fullPage: true });
if (await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Landing mobile overflow');
await mobile.locator('.home-room-list #room-directory').scrollIntoViewIfNeeded();
if (!await mobile.locator('#room-directory').isVisible()) throw new Error('Mobile homepage must show the room list without another menu');
if (await mobile.locator('#watch-menu').count()) throw new Error('Homepage room list must not require a modal entry point');
await mobile.goto(`${base}?room=ABCD2345`);
if (!await mobile.locator('#join-form').isVisible() || await mobile.locator('#room-input').inputValue() !== 'ABCD2345') throw new Error('Invitation must open join form');
await browser.close();
const fallbackBrowser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'chrome', headless: true, args: ['--disable-webgl'] });
const fallbackPage = await fallbackBrowser.newPage();
await fallbackPage.goto(base);
await fallbackPage.locator('#quick-settings > summary').click();
await fallbackPage.getByRole('button', { name: 'WebGL 不可用，已自动使用二维界面' }).waitFor();
await fallbackPage.locator('#quick-settings > summary').click();
await fallbackPage.locator('#practice').click();
await fallbackPage.locator('#start').click();
await fallbackPage.locator('.hand .card').first().waitFor();
await fallbackPage.locator('.table-trump').waitFor();
await expect(fallbackPage.locator('.trump-card')).toHaveCount(0);
if (await fallbackPage.locator('.trump-marker').count()) throw new Error('2D mode retains the old corner trump marker');
await fallbackBrowser.close();
console.log(JSON.stringify({ practice: '5-round game complete with fixed host-selected rules and WebGL', mobile: 'no overflow', fallback: '2D game starts without WebGL', errors }));
if (errors.length) process.exitCode = 1;
